#!/usr/bin/env bash
# Builds a self-contained, double-clickable macOS app bundle for hand testing:
# the vendored LÖVE runtime plus a product-mode snapshot of the repository
# sources under Contents/Resources/repo. Saves and generated data keep the
# product identity ("portemon"), so they live in the user's Application Support
# directory and survive rebuilds.
set -euo pipefail
cd "$(dirname "$0")/.."

if [ "$(uname -s)" != "Darwin" ]; then
  echo "build-macos: requires macOS" >&2
  exit 1
fi

LOVE_APP="scripts/bin/love.app"
if [ ! -x "$LOVE_APP/Contents/MacOS/love" ]; then
  echo "build-macos: missing $LOVE_APP; run scripts/lib/repo-setup.sh first" >&2
  exit 1
fi

BUNDLE_NAME="Portémon Nitro.app"
BUILD_DIR=".cache/build"
APP="$BUILD_DIR/$BUNDLE_NAME"

rm -rf -- "$APP"
mkdir -p -- "$BUILD_DIR"
cp -R "$LOVE_APP" "$APP"
mv "$APP/Contents/MacOS/love" "$APP/Contents/MacOS/love-core"

# Product-mode snapshot: the LÖVE source root (app/) plus every repo-root
# package the running game requires. Not shipped: tooling, tests, vendor types,
# and contributor-local generated state.
REPO="$APP/Contents/Resources/repo"
mkdir -p -- "$REPO"
for dir in app game libs romdump gen4 data; do
  cp -R "$dir" "$REPO/$dir"
done
rm -rf -- "$REPO/data/generated"

cat >"$APP/Contents/MacOS/portemon" <<'LAUNCH'
#!/bin/sh
# Generated by scripts/build-macos.sh: launches the bundled LÖVE runtime
# against the repository snapshot in Resources/repo (product mode).
HERE="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
exec "$HERE/love-core" "$HERE/../Resources/repo/app"
LAUNCH
chmod 0755 "$APP/Contents/MacOS/portemon"

PLIST="$APP/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleName Portémon Nitro" "$PLIST"
/usr/libexec/PlistBuddy -c "Set :CFBundleExecutable portemon" "$PLIST"
/usr/libexec/PlistBuddy -c "Set :CFBundleIdentifier org.portemon.nitro" "$PLIST"

# A locally modified bundle must lose any inherited quarantine mark and be
# re-signed ad hoc or Gatekeeper refuses to launch it.
xattr -dr com.apple.quarantine "$APP" 2>/dev/null || true
codesign --force --deep --sign - "$APP" 2>/dev/null

echo "build-macos: built $APP"
echo "build-macos: launch it (open \"$APP\") and drop your ROM onto the window to import"
